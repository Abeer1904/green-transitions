// Turns content/readings/*.md into src/generated/readings.ts.
// To add a reading: drop a .md file in content/readings/ with front matter, then rebuild.
import { readdir, readFile, writeFile, mkdir } from 'node:fs/promises';
import path from 'node:path';

const dir = 'content/readings';
const required = ['id', 'track', 'kind', 'order', 'minutes', 'title', 'summary'];
async function parse(file, keys) {
  const raw = await readFile(file, 'utf8');
  const m = raw.match(/^---\n([\s\S]*?)\n---\n([\s\S]*)$/);
  if (!m) throw new Error(`${file}: missing front matter`);
  const meta = {};
  for (const line of m[1].split('\n')) {
    const i = line.indexOf(':');
    if (i > 0) meta[line.slice(0, i).trim()] = line.slice(i + 1).trim();
  }
  for (const k of keys) if (!meta[k]) throw new Error(`${file}: front matter is missing "${k}"`);
  return { meta, body: m[2].trim() };
}
const entries = await readdir(dir, { withFileTypes: true });
const files = entries.filter(e => e.isFile() && e.name.endsWith('.md')).map(e => e.name).sort();
const readings = [];
for (const f of files) {
  const { meta, body } = await parse(path.join(dir, f), required);
  readings.push({ id: meta.id, track: meta.track, kind: meta.kind, order: Number(meta.order), minutes: Number(meta.minutes), title: meta.title, summary: meta.summary, source: meta.source || '', body });
}
const ids = new Set();
for (const r of readings) { if (ids.has(r.id)) throw new Error(`Duplicate reading id: ${r.id}`); ids.add(r.id); }
// Translations: content/readings/<lang>/*.md. Only id, title and summary are read from front matter;
// everything else comes from the English reading with the same id.
const text = {};
for (const d of entries.filter(e => e.isDirectory())) {
  text[d.name] = {};
  for (const f of (await readdir(path.join(dir, d.name))).filter(x => x.endsWith('.md')).sort()) {
    const { meta, body } = await parse(path.join(dir, d.name, f), ['id', 'title', 'summary']);
    if (!ids.has(meta.id)) throw new Error(`${d.name}/${f}: no English reading with id ${meta.id}`);
    text[d.name][meta.id] = { id: meta.id, title: meta.title, summary: meta.summary, body };
  }
}
await mkdir('src/generated', { recursive: true });
await writeFile('src/generated/readings-i18n.ts', `// Generated by scripts/gen-content.mjs. Do not edit.\nimport type { ReadingText } from '../content/overlay';\nexport const READING_TEXT: Record<string, Record<string, ReadingText>> = ${JSON.stringify(text, null, 1)};\n`);
await writeFile('src/generated/readings.ts', `// Generated by scripts/gen-content.mjs. Do not edit.\nimport type { Reading } from '../content/types';\nexport const READINGS: Reading[] = ${JSON.stringify(readings, null, 1)};\n`);
console.log(`Generated ${readings.length} readings.`);
